function routeOption(id, group, route, target, requirements, finalRequirements, successEnding, fallbackEnding, extra = {}) {
  return {
    id,
    group,
    route,
    target,
    label: `${route}：${target}`,
    requirements,
    finalRequirements: mergeRequirements(requirements, finalRequirements),
    successEnding,
    fallbackEnding,
    ...extra,
  };
}

function mergeRequirements(base = {}, extra = {}) {
  return {
    ...base,
    ...extra,
    attributes: {
      ...(base.attributes ?? {}),
      ...(extra.attributes ?? {}),
    },
  };
}
