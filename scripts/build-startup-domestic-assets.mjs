import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { deferredStartupBgmTracks, startupGateBgmTracks } from "../web-app/game/music.mjs";
import { ENDING_MEMORY_SCENE_IMAGE_SOURCES } from "../web-app/ui/ending-memory-assets.generated.mjs";
import {
  criticalStartupImageSources,
  opportunisticStartupImageSources,
  startupFailureEndingIllustrationSources,
  startupLoadingShellImageSources,
  startupRouteEndingIllustrationSources,
} from "../web-app/ui/resource-preload.mjs";
import { uiIconAtlasImageSources } from "../web-app/ui/ui-icon-atlas.mjs";

const projectRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const outputPath = resolve(projectRoot, "web-app/ui/startup-domestic-assets.mjs");
const CRITICAL_STARTUP_ASSET_PATHS = new Set([
  ...criticalStartupImageSources({ isMobileStartSurface: false }),
  ...criticalStartupImageSources({ isMobileStartSurface: true }),
]);
const R2_STARTUP_ASSET_PATHS = new Set(
  ENDING_MEMORY_SCENE_IMAGE_SOURCES.filter((source) => !CRITICAL_STARTUP_ASSET_PATHS.has(source)),
);
const SITE_STARTUP_ASSET_PATHS = new Set(startupLoadingShellImageSources());
const DOMESTIC_ROUTE_ENDING_ILLUSTRATION_PATHS = startupRouteEndingIllustrationSources();
const DOMESTIC_ENDING_ILLUSTRATION_PATHS = new Set([
  ...startupFailureEndingIllustrationSources(),
  ...DOMESTIC_ROUTE_ENDING_ILLUSTRATION_PATHS,
]);

export function buildStartupDomesticAssets() {
  const sources = [
    ...criticalStartupImageSources({ isMobileStartSurface: false }),
    ...criticalStartupImageSources({ isMobileStartSurface: true }),
    ...uiIconAtlasImageSources(),
    ...opportunisticStartupImageSources({ isMobileStartSurface: false }),
    ...startupGateBgmTracks().map((track) => track.src),
    ...deferredStartupBgmTracks().map((track) => track.src),
    ...DOMESTIC_ROUTE_ENDING_ILLUSTRATION_PATHS,
  ];

  const paths = [...new Set(sources.filter(isDomesticStartupAssetPath))].sort();
  writeFileSync(outputPath, generatedModule(paths));
  return { outputPath, count: paths.length };
}

function generatedModule(paths) {
  return `// Generated by scripts/build-startup-domestic-assets.mjs.\nexport const STARTUP_DOMESTIC_ASSET_PATHS = ${JSON.stringify(paths, null, 2)};\n`;
}

function isOptimizedAssetPath(source) {
  return typeof source === "string" && source.startsWith("/optimized/");
}

function isDomesticStartupAssetPath(source) {
  return isOptimizedAssetPath(source)
    && !SITE_STARTUP_ASSET_PATHS.has(source)
    && !isR2StartupAssetPath(source);
}

function isR2StartupAssetPath(source) {
  return (source.includes("/assets/ending-illustrations/") && !DOMESTIC_ENDING_ILLUSTRATION_PATHS.has(source))
    || R2_STARTUP_ASSET_PATHS.has(source);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = buildStartupDomesticAssets();
  console.log(`Wrote ${result.count} startup domestic asset paths to ${result.outputPath}`);
}
